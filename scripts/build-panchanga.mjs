// Builds public/circle/panchanga.js: the pañcāṅga engine, content, icons and city list as ONE plain browser file
// (window.EPPanchanga) for the Circle Today page, made from the same modules as /today/panchanga and /api/panchanga, so
// there is one copy of the maths. Run by `npm run build` (prebuild); `npm test` checks the committed file is up to date.
//   node scripts/build-panchanga.mjs          writes the file
//   import { bundle } from './build-panchanga.mjs'   returns the text
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'public/circle/panchanga.js');
const MODULES = ['engine', 'content', 'icons', 'places', 'describe']; // dependency order

export function bundle() {
  const parts = MODULES.map(name => {
    let src = fs.readFileSync(path.join(ROOT, 'lib/panchanga', name + '.js'), 'utf8');
    src = src.replace(/^import [^;]*;\n/gm, '');                    // the modules import each other: one scope instead
    src = src.replace(/^export (async function|function|const|let|class) /gm, '$1 ');
    if (/^\s*export\s/m.test(src)) throw new Error(`lib/panchanga/${name}.js uses an export form the bundler doesn't handle`);
    return `// ---- lib/panchanga/${name}.js ----\n${src.trim()}\n`;
  });
  return `/* Generated by scripts/build-panchanga.mjs from lib/panchanga/*.js. Do not edit; change those files and run the build.
   Today's pañcāṅga for the Circle Today page: window.EPPanchanga. */
(function () {
${parts.join('\n')}
window.EPPanchanga = { describeDay, sublineOf, fmtTime, relDay, tzParts, tzOffset, PLACES, ABOUT, RASHI_EN, moonPath, iconTithi, iconVara, iconNak, iconYoga, iconKarana };
})();
`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const text = bundle();
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) { fs.writeFileSync(OUT, text); console.log('panchanga bundle written (' + text.length + ' bytes)'); }
}
