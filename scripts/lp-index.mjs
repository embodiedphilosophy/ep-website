// Writes lib/lp/pages.js: one entry per folder in app/lp/ that has a page.js, so the landing-page feed
// (/api/landing-pages) and the sitemap list new pages on their own. Runs before every build and dev start
// (npm prebuild / predev). A folder's lp.js gives title, teacher, dates and checkout; without one, the title is
// read from the page's metadata and the page counts as evergreen.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dir = path.join(root, 'app/lp');
const slugs = fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true })
  .filter(d => d.isDirectory() && fs.existsSync(path.join(dir, d.name, 'page.js'))).map(d => d.name).sort() : [];

const lines = [], entries = [];
slugs.forEach((slug, i) => {
  const has = ['lp.js', 'lp.mjs'].find(f => fs.existsSync(path.join(dir, slug, f)));
  if (has) lines.push(`import m${i} from '@/app/lp/${slug}/${has.replace(/\.m?js$/, '')}';`);
  const src = fs.readFileSync(path.join(dir, slug, 'page.js'), 'utf8');
  const t = (src.match(/metadata\s*=\s*\{[\s\S]*?title:\s*(['"`])((?:\\.|(?!\1).)*)\1/) || [])[2] || '';
  const title = t.replace(/\s+—\s+(Pay What You Can\s+—\s+)?Embodied Philosophy\s*$/i, '').trim();
  entries.push(`  { slug: ${JSON.stringify(slug)}, title: ${JSON.stringify(title)}${has ? `, ...m${i}` : ''} },`);
});
const out = `// Generated by scripts/lp-index.mjs from the folders in app/lp/. Don't edit: it's rewritten on every build.\n${lines.join('\n')}${lines.length ? '\n' : ''}\nconst pages = [\n${entries.join('\n')}\n];\nexport default pages;\n`;
const file = path.join(root, 'lib/lp/pages.js');
if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) fs.writeFileSync(file, out);
console.log(`lp-index: ${slugs.length} landing page${slugs.length === 1 ? '' : 's'} (${slugs.join(', ')})`);
